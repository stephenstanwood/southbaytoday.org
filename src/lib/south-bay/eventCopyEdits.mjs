// Title normalization accents San José while some sources use San Jose.
// Fold that known place-name variant, preserving other language distinctions,
// and ignore end punctuation when comparing the complete fields.
export function isTitleOnlyDescription(title, description) {
  if (typeof title !== "string" || typeof description !== "string") return false;
  const normalize = text => text.normalize("NFC").toLowerCase()
    .replace(/\s+/g, " ").trim().replace(/[.!?]+$/u, "").trimEnd()
    .replace(/(?<![\p{L}\p{N}_])san josé(?![\p{L}\p{N}_])/gu, "san jose");
  return Boolean(normalize(title)) && normalize(title) === normalize(description);
}

/** Return an event with only its reviewed display-copy phrases repaired.
 * The source-text cache fingerprint must be computed before this display pass:
 * punctuation repairs do not warrant regenerating already source-bound blurbs. */
export function polishReviewedEventCopy(event) {
  const next = { ...event };
  if (isTitleOnlyDescription(next.title, next.description)) next.description = "";
  const fields = EDITS[event.source];
  if (!fields) return next;
  for (const [field, edits] of Object.entries(fields)) {
    if (typeof next[field] !== "string") continue;
    for (const [before, after] of edits) {
      // Remove only complete placeholder descriptions. Later substantive copy
      // can include the same phrase.
      if (after === "") {
        if (next[field] === before) next[field] = "";
      } else {
        next[field] = next[field].replaceAll(before, after);
      }
    }
  }
  // The library keeps this boilerplate in its description after registration fills or closes.
  const signupNote = `${SJPL_ONLINE_SIGNUP_COPY} Space is limited.`;
  if (next.source === "San Jose Public Library" && ["full", "closed"].includes(next.registration)
      && next.attendanceNote?.includes(signupNote)) {
    next.attendanceNote = next.attendanceNote.replace(signupNote, "").trim() || undefined;
  }
  // The library keeps the series signup instructions in the description
  // after the source's occurrence-level registration window has closed.
  if (next.source === "Palo Alto City Library" && next.title === "Learn English: Beyond the Basics"
      && next.registration === "closed" && typeof next.description === "string") {
    next.description = next.description.replace(
      /\bRegister once for the full \d+-week series and double-check your email address\. Registration closes in the \d+(?:st|nd|rd|th) week\./g,
      "Registration for this series is closed.",
    );
  }
  // This series' invitation to register can remain in the source after the session fills.
  if (next.source === "Santa Clara County Library" && next.title === "Tween Dungeons and Dragons"
      && next.registration === "full") {
    if (typeof next.description === "string") {
      next.description = next.description.replace(
        /^Please see contact information to receive information on registration and future Tween Dungeons and Dragons sessions\./,
        "See the event's contact information for details on future Tween Dungeons and Dragons sessions.",
      ).replace(
        /Join our quest for valor! Kids ages (\d+-\d+) are invited to register for our Winter Session of Tween Dungeons and Dragons\. Our Winter Session is designed for players already familiar with the basics of the game\./,
        "The winter session is for kids ages $1 who already know the basics of the game.",
      );
    }
    if (typeof next.blurb === "string") {
      next.blurb = next.blurb.replace(
        /^Play Dungeons and Dragons with other kids ages (\d+-\d+) in the library's Winter Session, with registration handled through the listed contact\.$/,
        "The library's winter Dungeons and Dragons session is for kids ages $1.",
      );
    }
  }
  // The series description lists every topic. Lead with the confirmed lesson for this occurrence.
  if (next.source === "San Jose Public Library" && next.date === "2026-11-28"
      && typeof next.description === "string" && next.description.includes(SJPL_EASY_TECH_VOICE_ASSISTANT_COPY)
      && next.blurb === "Learn new tech skills in an interactive group session led by Malhar, a local high school student who helps seniors with technology.") {
    next.blurb = "Practice using Siri or Google Assistant to check the weather, set timers, and make calls. Malhar, a local high school student, leads this group class for older adults.";
  }
  return next;
}
